/* gen_key.c - generate a Falcon-512 keypair on the HOST and emit it as a
 * C header for embedding in the CVA6 benchmark.
 *
 * Built against the SAME pinned config.h as the target (FALCON_FPEMU=1,
 * FALCON_KG_CHACHA20=0).  FPEMU is pure integer arithmetic, so the key is
 * bit-identical to what the RISC-V build would produce from the same seed.
 * That is what makes the checksum cross-check meaningful.
 */
#include <stdio.h>
#include <stdint.h>
#include <string.h>
#include <time.h>
#include "falcon.h"

#ifndef LOGN
#define LOGN 9        /* override with -DLOGN=10 for Falcon-1024 */
#endif
#define SEED "cva6-falcon-bench"
#define SEED_LEN 17

static uint8_t privkey[FALCON_PRIVKEY_SIZE(LOGN)];
static uint8_t pubkey [FALCON_PUBKEY_SIZE(LOGN)];
static uint8_t tmp    [FALCON_TMPSIZE_KEYGEN(LOGN)];

/* identical to bench_falcon.c so the checksums are comparable */
static uint32_t fnv1a(const uint8_t *p, size_t n) {
    uint32_t h = 2166136261u;
    while (n--) { h ^= *p++; h *= 16777619u; }
    return h;
}

static void emit(FILE *f, const char *name, const uint8_t *p, size_t n) {
    fprintf(f, "static const uint8_t %s[%zu] = {\n", name, n);
    for (size_t i = 0; i < n; i++) {
        if (i % 12 == 0) fprintf(f, "   ");
        fprintf(f, " 0x%02x,", p[i]);
        if (i % 12 == 11) fprintf(f, "\n");
    }
    if (n % 12) fprintf(f, "\n");
    fprintf(f, "};\n\n");
}

int main(int argc, char **argv) {
    shake256_context rng;
    clock_t t0, t1;
    int r;

    if (argc < 2) { fprintf(stderr, "usage: %s <out.h>\n", argv[0]); return 2; }

    shake256_init_prng_from_seed(&rng, SEED, SEED_LEN);

    t0 = clock();
    r = falcon_keygen_make(&rng, LOGN,
                           privkey, sizeof privkey,
                           pubkey,  sizeof pubkey,
                           tmp,     sizeof tmp);
    t1 = clock();
    if (r != 0) { fprintf(stderr, "keygen failed: %d\n", r); return 1; }

    double ms = 1000.0 * (double)(t1 - t0) / CLOCKS_PER_SEC;
    fprintf(stderr, "host keygen: %.1f ms\n", ms);
    fprintf(stderr, "PRIVKEY_CHECKSUM=%u\n", fnv1a(privkey, sizeof privkey));
    fprintf(stderr, "PUBKEY_CHECKSUM=%u\n",  fnv1a(pubkey,  sizeof pubkey));

    FILE *f = fopen(argv[1], "w");
    if (!f) { perror("fopen"); return 1; }
    fprintf(f, "/* GENERATED by host/gen_key.c - do not edit.\n"
               " * Falcon-512 keypair from seed \"%s\".\n"
               " * Built with FALCON_FPEMU=1, FALCON_KG_CHACHA20=0, so this is\n"
               " * bit-identical to what the RISC-V target would generate.\n"
               " *   PRIVKEY_CHECKSUM = %u\n"
               " *   PUBKEY_CHECKSUM  = %u\n"
               " */\n#ifndef FALCON_KEY_H\n#define FALCON_KEY_H\n#include <stdint.h>\n\n",
            SEED, fnv1a(privkey, sizeof privkey), fnv1a(pubkey, sizeof pubkey));
    fprintf(f, "#define EMBEDDED_KEY_LOGN %d\n\n", LOGN);
    emit(f, "falcon512_privkey", privkey, sizeof privkey);
    emit(f, "falcon512_pubkey",  pubkey,  sizeof pubkey);
    fprintf(f, "#define EMBEDDED_PRIVKEY_CHECKSUM %uu\n", fnv1a(privkey, sizeof privkey));
    fprintf(f, "#define EMBEDDED_PUBKEY_CHECKSUM  %uu\n", fnv1a(pubkey,  sizeof pubkey));
    fprintf(f, "\n#endif\n");
    fclose(f);
    fprintf(stderr, "wrote %s\n", argv[1]);
    return 0;
}
